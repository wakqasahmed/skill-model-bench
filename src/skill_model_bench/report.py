"""Build an evidence-labeled report from promptfoo's JSON eval output.

promptfoo's ``eval --output results.json`` (or the equivalent
``--output json``) shape, confirmed against a real example generated by
promptfoo itself
(https://github.com/promptfoo/promptfoo/blob/main/examples/simple-cli/output.json,
also documented at https://www.promptfoo.dev/docs/configuration/outputs/):

    {
      "evalId": "...",
      "results": {
        "results": [
          {
            "provider": {"id": "openrouter:openai/gpt-4o-mini", "label": ""},
            "success": true,
            "score": 1,
            "cost": 0.0000046,
            "latencyMs": 3,
            "gradingResult": {"pass": true, "score": 1, "reason": "..."},
            "testCase": {
              "vars": {...},
              "assert": [...],
              "metadata": {"ground_truth": "fixture", "scenario_id": "..."}
            },
            ...
          },
          ...
        ]
      },
      "config": {...}
    }

Per-test-case results live at ``results.results[]``. Pass/fail is the
top-level boolean ``success`` field (mirrored in ``gradingResult.pass``).
Cost lives in the top-level ``cost`` field of each result (also mirrored
under ``response.cost``). Latency lives in the top-level ``latencyMs``
field. The provider/model that produced a result is identified by
``provider.id`` (e.g. ``"openrouter:openai/gpt-4o-mini"``, matching the
``openrouter:<model>`` ids this repo's ``config_gen.py`` writes as
providers). Each test case's original ``metadata`` -- including the
``ground_truth`` value ``config_gen.py`` set to ``"fixture"`` or
``"judge"`` -- round-trips back unchanged under ``testCase.metadata``.
"""

import json
from pathlib import Path
from typing import Any, Dict, List, Optional, Union

DEFAULT_QUALITY_BAR = 0.8


def _load_raw(source: Union[str, Path, Dict[str, Any]]) -> Dict[str, Any]:
    if isinstance(source, dict):
        return source
    path = Path(source)
    return json.loads(path.read_text())


def _iter_results(raw: Dict[str, Any]) -> List[Dict[str, Any]]:
    results_section = raw.get("results", raw)
    if isinstance(results_section, dict):
        results = results_section.get("results", [])
    elif isinstance(results_section, list):
        results = results_section
    else:
        results = []
    return results if isinstance(results, list) else []


def _provider_id(result: Dict[str, Any]) -> str:
    provider = result.get("provider")
    if isinstance(provider, dict):
        return provider.get("id", "unknown-provider")
    if isinstance(provider, str):
        return provider
    return "unknown-provider"


def _passed(result: Dict[str, Any]) -> bool:
    if "success" in result:
        return bool(result["success"])
    grading_result = result.get("gradingResult") or {}
    return bool(grading_result.get("pass", False))


def _cost(result: Dict[str, Any]) -> float:
    if "cost" in result and result["cost"] is not None:
        return float(result["cost"])
    response = result.get("response") or {}
    return float(response.get("cost") or 0.0)


def _latency_ms(result: Dict[str, Any]) -> float:
    return float(result.get("latencyMs") or 0.0)


def _ground_truth(result: Dict[str, Any]) -> Optional[str]:
    test_case = result.get("testCase") or {}
    metadata = test_case.get("metadata") or {}
    return metadata.get("ground_truth")


def build_report(
    source: Union[str, Path, Dict[str, Any]],
    quality_bar: float = DEFAULT_QUALITY_BAR,
) -> Dict[str, Any]:
    """Parse promptfoo JSON output and build an evidence-labeled report.

    Args:
        source: A parsed promptfoo results dict, or a path to a JSON file
            produced by ``promptfoo eval --output results.json``.
        quality_bar: Minimum pass rate a model must clear to be
            recommendable. Defaults to 0.8.

    Returns:
        A JSON-serializable dict with per-model stats (pass rate, total
        cost, average latency, fixture/judge evidence split) and a
        recommendation for the cheapest model clearing the bar, or an
        explicit "no qualifying model" result if none does.
    """
    raw = _load_raw(source)
    results = _iter_results(raw)

    per_model: Dict[str, Dict[str, Any]] = {}
    for result in results:
        model = _provider_id(result)
        bucket = per_model.setdefault(
            model,
            {
                "total_tests": 0,
                "passed_tests": 0,
                "total_cost": 0.0,
                "total_latency_ms": 0.0,
                "fixture_count": 0,
                "judge_count": 0,
                "unlabeled_count": 0,
            },
        )
        bucket["total_tests"] += 1
        if _passed(result):
            bucket["passed_tests"] += 1
        bucket["total_cost"] += _cost(result)
        bucket["total_latency_ms"] += _latency_ms(result)

        ground_truth = _ground_truth(result)
        if ground_truth == "fixture":
            bucket["fixture_count"] += 1
        elif ground_truth == "judge":
            bucket["judge_count"] += 1
        else:
            bucket["unlabeled_count"] += 1

    models: Dict[str, Any] = {}
    for model, bucket in per_model.items():
        total_tests = bucket["total_tests"]
        pass_rate = bucket["passed_tests"] / total_tests if total_tests else 0.0
        avg_latency_ms = (
            bucket["total_latency_ms"] / total_tests if total_tests else 0.0
        )
        fixture_count = bucket["fixture_count"]
        judge_count = bucket["judge_count"]
        unlabeled_count = bucket["unlabeled_count"]

        fixture_fraction = fixture_count / total_tests if total_tests else 0.0
        judge_fraction = judge_count / total_tests if total_tests else 0.0
        unlabeled_fraction = unlabeled_count / total_tests if total_tests else 0.0

        if total_tests and judge_count == total_tests:
            evidence = "judge_only"
        elif total_tests and fixture_count == total_tests:
            evidence = "fixture_only"
        elif fixture_count and judge_count:
            evidence = "mixed"
        else:
            evidence = "unlabeled"

        models[model] = {
            "total_tests": total_tests,
            "passed_tests": bucket["passed_tests"],
            "pass_rate": pass_rate,
            "total_cost": bucket["total_cost"],
            "avg_latency_ms": avg_latency_ms,
            "fixture_count": fixture_count,
            "judge_count": judge_count,
            "unlabeled_count": unlabeled_count,
            "fixture_fraction": fixture_fraction,
            "judge_fraction": judge_fraction,
            "unlabeled_fraction": unlabeled_fraction,
            "evidence": evidence,
            "judge_only_warning": evidence == "judge_only",
        }

    recommendation = _recommend(models, quality_bar)

    return {
        "quality_bar": quality_bar,
        "models": models,
        "recommendation": recommendation,
    }


def _recommend(models: Dict[str, Any], quality_bar: float) -> Dict[str, Any]:
    qualifying = [
        (model, stats)
        for model, stats in models.items()
        if stats["pass_rate"] >= quality_bar
    ]

    if not qualifying:
        return {
            "model": None,
            "qualifies": False,
            "reason": (
                f"No model reached the quality bar of {quality_bar:.0%} pass rate. "
                "No qualifying config."
            ),
        }

    qualifying.sort(key=lambda item: item[1]["total_cost"])
    cheapest_model, cheapest_stats = qualifying[0]

    reason = (
        f"{cheapest_model} is the cheapest model clearing the {quality_bar:.0%} "
        f"quality bar (pass rate {cheapest_stats['pass_rate']:.0%}, "
        f"total cost {cheapest_stats['total_cost']:.6f})."
    )
    if cheapest_stats["evidence"] == "judge_only":
        reason += (
            " Note: this model's pass rate is judge-scored only (no fixtures "
            "existed for this skill) -- weaker evidence than a fixture-backed "
            "pass rate."
        )

    return {
        "model": cheapest_model,
        "qualifies": True,
        "reason": reason,
    }


def _evidence_label(stats: Dict[str, Any]) -> str:
    fixture_pct = stats["fixture_fraction"] * 100
    judge_pct = stats["judge_fraction"] * 100
    label = f"{fixture_pct:.0f}% fixture / {judge_pct:.0f}% judge"
    if stats["unlabeled_count"]:
        label += f" / {stats['unlabeled_fraction'] * 100:.0f}% unlabeled"
    if stats["evidence"] == "judge_only":
        label += " (judge-only -- weaker evidence)"
    return label


def render_markdown(report: Dict[str, Any]) -> str:
    """Render a report dict (from build_report) as a Markdown table + summary."""
    lines: List[str] = []
    lines.append("# Model benchmark report")
    lines.append("")
    lines.append(f"Quality bar: **{report['quality_bar']:.0%}** pass rate")
    lines.append("")
    lines.append(
        "| Model | Pass Rate | Ground Truth Evidence | Total Cost | Avg Latency (ms) |"
    )
    lines.append("|---|---|---|---|---|")

    for model, stats in sorted(
        report["models"].items(), key=lambda item: item[1]["total_cost"]
    ):
        lines.append(
            f"| {model} | {stats['pass_rate']:.0%} "
            f"({stats['passed_tests']}/{stats['total_tests']}) | "
            f"{_evidence_label(stats)} | "
            f"{stats['total_cost']:.6f} | {stats['avg_latency_ms']:.1f} |"
        )

    lines.append("")

    judge_only_models = [
        model
        for model, stats in report["models"].items()
        if stats["evidence"] == "judge_only"
    ]
    if judge_only_models:
        lines.append(
            "**Weaker evidence warning:** the following models' pass rates are "
            "judge-scored only -- no fixtures existed for this skill, so these "
            "numbers are weaker evidence than a fixture-backed pass rate: "
            + ", ".join(sorted(judge_only_models))
            + "."
        )
        lines.append("")

    recommendation = report["recommendation"]
    lines.append("## Recommendation")
    lines.append("")
    if recommendation["qualifies"]:
        lines.append(f"**{recommendation['model']}** -- {recommendation['reason']}")
    else:
        lines.append(f"No qualifying config. {recommendation['reason']}")

    return "\n".join(lines) + "\n"
